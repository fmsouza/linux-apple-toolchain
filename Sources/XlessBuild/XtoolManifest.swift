import Foundation
import XlessCore

/// Generates xtool.yml (schema: xtool Sources/PackLib/PackSchema.swift) from xless.yml.
public enum XtoolManifest {
    public static let marker = "# generated by xless — edit xless.yml instead"

    public static func yaml(config: ProjectConfig) throws -> String {
        let ios = try config.platform(.ios)
        var lines = [marker, "version: 1", "bundleID: \(config.bundleID(for: .ios))", "product: \(ios.product)"]
        if let info = config.infoPlist { lines.append("infoPath: \(info)") }
        if let privacy = config.privacyManifest { lines += ["resources:", "  - \(privacy)"] }
        return lines.joined(separator: "\n") + "\n"
    }

    public static func write(config: ProjectConfig, project: URL) throws {
        let url = project.appendingPathComponent("xtool.yml")
        if let existing = try? String(contentsOf: url, encoding: .utf8), !existing.hasPrefix(marker) {
            throw XlessError(.build, "\(url.path) exists and was not generated by xless",
                             fix: "move its settings into xless.yml and delete xtool.yml")
        }
        try yaml(config: config).write(to: url, atomically: true, encoding: .utf8)
    }
}
