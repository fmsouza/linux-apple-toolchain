private var fm: FileManager { .default }

private func scratch() throws -> URL {
    let dir = fm.temporaryDirectory.appendingPathComponent("bundler-\(UUID().uuidString)", isDirectory: true)
    try fm.createDirectory(at: dir, withIntermediateDirectories: true)
    return dir
}

private func put(_ root: URL, _ path: String, _ text: String) throws {
    let url = root.appendingPathComponent(path)
    try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    try text.write(to: url, atomically: true, encoding: .utf8)
}

private func resolved(_ platform: Platform, iosExtra: String = "", macExtra: String = "", plistVars: String = "plistVars: { BUILD_SHA: \"@GIT_SHA@\" }") throws -> ResolvedCargo {
    let overlay = try CargoOverlay.parse(yaml: """
    type: cargo
    bundleID: com.example.hello
    teamID: ABCDE12345
    version: "0.10.0-rc.1"
    build: "42"
    \(plistVars)
    inputs:
      - { name: craft-fonts, path: /unused, env: FONTS_DIR }
    ios:
      package: hello-mobile
      product: Hello
      minimumOS: "17.0"
      assets: Assets.xcassets
      infoPlist: ios/Info.plist
    \(iosExtra)
    macos:
      bundleID: com.example.hello.mac
      package: hello
      product: Hello
      minimumOS: "11.0"
      icon: hello.icns
      infoPlist: mac/Info.plist.in
    \(macExtra)
    """, name: "hello")
    return try CargoProject.resolve(overlay: overlay, platform: platform, source: fm.temporaryDirectory)
}

private let vars = ["SHORT_VERSION": "0.10.0", "VERSION": "0.10.0-rc.1", "GIT_SHA": "deadbeef"]

private func read(_ url: URL) throws -> [String: Any] { try Plist.read(url, stage: .build) }

private func expectBuildError(containing needles: [String] = [], _ body: () throws -> Void, sourceLocation: SourceLocation = #_sourceLocation) {
    do {
        try body()
        Issue.record("expected a build error", sourceLocation: sourceLocation)
    } catch let e as XlessError {
        #expect(e.stage == .build, sourceLocation: sourceLocation)
        for n in needles { #expect(e.cause.contains(n), "cause: \(e.cause)", sourceLocation: sourceLocation) }
    } catch { Issue.record("unexpected error \(error)", sourceLocation: sourceLocation) }
}

private let macTemplate = """
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleIdentifier</key><string>com.old.id</string>
<key>CFBundleExecutable</key><string>OldName</string>
<key>CFBundleShortVersionString</key><string>@SHORT_VERSION@</string>
<key>AppVersion</key><string>@VERSION@</string>
<key>AppBuildCommit</key><string>@BUILD_SHA@</string>
</dict></plist>
"""

@Suite struct CargoBundlerTests {
    @Test func macInfoPlistFromTemplate() throws {
        let work = try scratch()
        try put(work, "mac/Info.plist.in", macTemplate)
        let info = try CargoBundler.infoPlist(resolved: resolved(.macos), platform: .macos, work: work, inputs: [:], vars: vars)
        #expect(info["CFBundleIdentifier"] as? String == "com.example.hello.mac")
        #expect(info["CFBundleExecutable"] as? String == "Hello")
        #expect(info["CFBundleName"] as? String == "Hello")
        #expect(info["CFBundleShortVersionString"] as? String == "0.10.0")
        #expect(info["CFBundleVersion"] as? String == "42")
        #expect(info["CFBundlePackageType"] as? String == "APPL")
        #expect(info["CFBundleInfoDictionaryVersion"] as? String == "6.0")
        #expect(info["AppVersion"] as? String == "0.10.0-rc.1")
        #expect(info["AppBuildCommit"] as? String == "deadbeef")
        #expect(info["LSMinimumSystemVersion"] as? String == "11.0")
        #expect(info["CFBundleIconFile"] as? String == "Hello")
    }

    @Test func templateWithXMLCommentsInsideTheDictParsesAndExpands() throws {
        let work = try scratch()
        let commented = """
            <?xml version="1.0" encoding="UTF-8"?>
            <!-- generated by hand -->
            <plist version="1.0"><dict>
            <!-- identity -->
            <key>CFBundleIdentifier</key><string>com.old.id</string>
            <!-- shown in About: @VERSION@ -->
            <key>AppVersion</key><string>@VERSION@</string>
            <key>AppBuildCommit</key><!-- the commit --><string>@BUILD_SHA@</string>
            </dict></plist>
            """
        try put(work, "mac/Info.plist.in", commented)
        let info = try CargoBundler.infoPlist(resolved: resolved(.macos), platform: .macos, work: work, inputs: [:], vars: vars)
        #expect(info["AppVersion"] as? String == "0.10.0-rc.1")
        #expect(info["AppBuildCommit"] as? String == "deadbeef")
        #expect(info["CFBundleIdentifier"] as? String == "com.example.hello.mac")
    }

    @Test func existingBundleNameIsKept() throws {
