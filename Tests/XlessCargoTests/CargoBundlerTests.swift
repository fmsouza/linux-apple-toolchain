    @Test func wildcardMatching() {
        func m(_ p: String, _ t: String) -> Bool { CargoBundler.wildcard(Array(p.unicodeScalars), Array(t.unicodeScalars)) }
        #expect(m("*", "") && m("*.ttf", "a.ttf") && m("a*b*c", "aXbYc") && m("OFL.txt", "OFL.txt"))
        #expect(!m("*.ttf", "a.otf") && !m("a*b", "ac") && !m("abc", "ab"))
    }
