    @Test func binaryTemplateAndInputTemplate() throws {
        let work = try scratch(), input = try scratch()
        let dict: [String: Any] = ["AppVersion": "@VERSION@"]
        try PropertyListSerialization.data(fromPropertyList: dict, format: .binary, options: 0)
            .write(to: { try fm.createDirectory(at: input.appendingPathComponent("p"), withIntermediateDirectories: true); return input.appendingPathComponent("p/Info.plist") }())
        let r = try resolved(.ios, iosExtra: "")
        var ios = r
        ios.platform.infoPlist = "input:craft-fonts/p/Info.plist"
        let info = try CargoBundler.infoPlist(resolved: ios, platform: .ios, work: work, inputs: ["craft-fonts": input], vars: vars)
        #expect(info["AppVersion"] as? String == "0.10.0-rc.1")
        expectBuildError(containing: ["craft-fonts"]) { _ = try CargoBundler.infoPlist(resolved: ios, platform: .ios, work: work, inputs: [:], vars: vars) }
    }

    @Test func iosBundleLayout() throws {
        let work = try scratch(), out = try scratch()
        try put(work, "ios/Info.plist", "<plist version=\"1.0\"><dict/></plist>")
        let exe = out.appendingPathComponent("hello-bin")
        try Data([0xCF, 0xFA]).write(to: exe)
        let privacy = out.appendingPathComponent("PrivacyInfo.xcprivacy")
        try Data("<plist/>".utf8).write(to: privacy)
        let app = try CargoBundler.assemble(resolved: resolved(.ios), platform: .ios, work: work, inputs: [:], vars: vars, executable: exe, privacyManifest: privacy, into: out)
        #expect(app.lastPathComponent == "Hello.app")
        let binary = app.appendingPathComponent("Hello")
        #expect(try Data(contentsOf: binary) == Data([0xCF, 0xFA]))
        #expect(try fm.attributesOfItem(atPath: binary.path)[.posixPermissions] as? Int == 0o755)
        #expect(fm.fileExists(atPath: app.appendingPathComponent("PrivacyInfo.xcprivacy").path))
        #expect(try String(contentsOf: app.appendingPathComponent("PkgInfo"), encoding: .utf8) == "APPL????")
        let info = try read(app.appendingPathComponent("Info.plist"))
        #expect(info["UIDeviceFamily"] as? [Int] == [1, 2])
        #expect(info["CFBundleExecutable"] as? String == "Hello")
        // XML, as the other bundlers write it.
        #expect(try String(contentsOf: app.appendingPathComponent("Info.plist"), encoding: .utf8).contains("<?xml"))
    }

    @Test func macBundleLayout() throws {
        let work = try scratch(), out = try scratch()
        try put(work, "mac/Info.plist.in", macTemplate)
        try put(work, "hello.icns", "icns")
        let exe = out.appendingPathComponent("hello-bin")
        try Data([1]).write(to: exe)
        let app = try CargoBundler.assemble(resolved: resolved(.macos), platform: .macos, work: work, inputs: [:], vars: vars, executable: exe,
                                            privacyManifest: URL(fileURLWithPath: "/nonexistent"), into: out)
        let binary = app.appendingPathComponent("Contents/MacOS/Hello")
        #expect(try fm.attributesOfItem(atPath: binary.path)[.posixPermissions] as? Int == 0o755)
        #expect(try String(contentsOf: app.appendingPathComponent("Contents/Resources/Hello.icns"), encoding: .utf8) == "icns")
        #expect(try read(app.appendingPathComponent("Contents/Info.plist"))["CFBundleIconFile"] as? String == "Hello")
        #expect(fm.fileExists(atPath: app.appendingPathComponent("Contents/PkgInfo").path))
        #expect(!fm.fileExists(atPath: app.appendingPathComponent("PrivacyInfo.xcprivacy").path))
    }

