    @Test func resourcesFromInputGlob() throws {
        let work = try scratch(), out = try scratch(), fonts = try scratch()
        try put(work, "mac/Info.plist.in", macTemplate)
        try put(work, "hello.icns", "icns")
        try put(fonts, "fonts/Alpha/OFL.txt", "alpha")
        try put(fonts, "fonts/Beta/OFL.txt", "beta")
        try put(fonts, "fonts/Gamma/README.txt", "no licence")
        try put(fonts, "fonts/.Hidden/OFL.txt", "hidden")
        let exe = out.appendingPathComponent("hello-bin")
        try Data([1]).write(to: exe)
        let r = try resolved(.macos, macExtra: """
          resources:
            - { from: "input:craft-fonts/fonts/*/OFL.txt", to: "Licenses/" }
        """)
        let app = try CargoBundler.assemble(resolved: r, platform: .macos, work: work, inputs: ["craft-fonts": fonts], vars: vars, executable: exe, privacyManifest: nil, into: out)
        let licenses = app.appendingPathComponent("Contents/Resources/Licenses")
        #expect(try fm.contentsOfDirectory(atPath: licenses.path).sorted() == ["Alpha-OFL.txt", "Beta-OFL.txt"])
        #expect(try String(contentsOf: licenses.appendingPathComponent("Beta-OFL.txt"), encoding: .utf8) == "beta")
    }

    @Test func plainFileAndDirectoryResources() throws {
        let work = try scratch(), out = try scratch()
        try put(work, "ios/Info.plist", "<plist version=\"1.0\"><dict/></plist>")
        try put(work, "res/LICENSE", "lic")
        try put(work, "res/data/a/b.txt", "b")
        let exe = out.appendingPathComponent("hello-bin")
        try Data([1]).write(to: exe)
        let r = try resolved(.ios, iosExtra: """
          resources:
            - { from: res/LICENSE, to: Legal/ }
            - { from: res/LICENSE, to: Legal/COPYING.txt }
            - { from: res/data, to: Data }
        """)
        let app = try CargoBundler.assemble(resolved: r, platform: .ios, work: work, inputs: [:], vars: vars, executable: exe, privacyManifest: nil, into: out)
        #expect(fm.fileExists(atPath: app.appendingPathComponent("Legal/LICENSE").path))
        #expect(fm.fileExists(atPath: app.appendingPathComponent("Legal/COPYING.txt").path))
        #expect(try String(contentsOf: app.appendingPathComponent("Data/a/b.txt"), encoding: .utf8) == "b")
    }

    @Test func missingResourceFails() throws {
        let work = try scratch(), out = try scratch()
        try put(work, "ios/Info.plist", "<plist version=\"1.0\"><dict/></plist>")
        try put(work, "res/x.txt", "x")
