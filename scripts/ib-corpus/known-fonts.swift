// Writes Sources/XlessIB/Lowering/Rules/KnownFonts.swift: the PostScript and family names, lowercased, of the fonts
// that ship with macOS and with the iOS simulator runtime. Mac only; run it through scripts/ib-corpus/known-fonts.sh.
//
// Usage: swift scripts/ib-corpus/known-fonts.swift <output.swift> [--available <names.txt>]... <font dir>...
//   <font dir>: every font file below it contributes the PostScript and family names of its faces (name tables, via
//     CoreText), except names starting with "." (those are refused by prefix);
//   --available: "<PostScript name>\t<family>" lines from available-font-names.swift (CoreText's available fonts
//     under /System, on the Mac or in the simulator), which add aliases that no name table has (PingFang*).
//
// Why (docs/research/nib-encoding.md, "UIFont and UIFontDescriptor"): ibtool encodes a custom font it resolves with
// that font's own traits, and any other name in a fixed "not resolved" form. The set of names ibtool resolves is not
// a simple rule over these sources (some fonts in both sets do not resolve, some Mac-only or runtime-only names do),
// so the compiler refuses every name in any of them: a deny-list. A resolvable name missing from every source would
// be mis-encoded; see the residual risk in nib-encoding.md.
import CoreText
import Foundation

var args = Array(CommandLine.arguments.dropFirst())
func usage() -> Never {
    FileHandle.standardError.write("usage: known-fonts.swift <output.swift> [--available <names.txt>]... <font dir>...\n".data(using: .utf8)!)
    exit(2)
}
guard args.count >= 2 else { usage() }
let output = args.removeFirst()
var names = Set<String>()
var dirs: [String] = []
while !args.isEmpty {
    let a = args.removeFirst()
    if a == "--available" {
        guard !args.isEmpty, let text = try? String(contentsOfFile: args.removeFirst(), encoding: .utf8) else { usage() }
        for line in text.split(separator: "\n") {
            for n in line.split(separator: "\t") where !n.hasPrefix(".") { names.insert(n.lowercased()) }
        }
    } else {
        dirs.append(a)
    }
}
guard !dirs.isEmpty else { usage() }
for dir in dirs {
    guard let e = FileManager.default.enumerator(at: URL(fileURLWithPath: dir), includingPropertiesForKeys: nil) else {
        FileHandle.standardError.write("cannot read \(dir)\n".data(using: .utf8)!)
        exit(1)
    }
    for case let url as URL in e where ["ttf", "ttc", "otf", "otc"].contains(url.pathExtension.lowercased()) {
        guard let descriptors = CTFontManagerCreateFontDescriptorsFromURL(url as CFURL) as? [CTFontDescriptor] else { continue }
        for d in descriptors {
            for attribute in [kCTFontNameAttribute, kCTFontFamilyNameAttribute] {
                if let n = CTFontDescriptorCopyAttribute(d, attribute) as? String, !n.hasPrefix(".") { names.insert(n.lowercased()) }
            }
        }
    }
}
let sorted = names.sorted()
precondition(sorted.allSatisfy { !$0.contains("\\") && !$0.contains("\"\"\"") && !$0.contains("\n") }, "unexpected character in a font name")
let body = sorted.map { "        \($0)" }.joined(separator: "\n")
let source = """
// Generated by scripts/ib-corpus/known-fonts.swift; do not edit. \(sorted.count) names.

/// PostScript and family names (lowercased) of the fonts shipped with macOS 27 and the iOS 27.0 simulator runtime,
/// from their font files and from CoreText's available fonts under /System on both. A custom font with one of these
/// names may resolve in ibtool and get that font's own encoding, which is not reproduced, so `FontRule` refuses it
/// (a deny-list; docs/research/nib-encoding.md, open question 3).
enum KnownFonts {
    static let names: Set<String> = Set(list.split(separator: "\\n").map(String.init))

    private static let list = \"\"\"
\(body)
        \"\"\"
}

"""
try source.write(toFile: output, atomically: true, encoding: .utf8)
print("known-fonts: \(sorted.count) names -> \(output)")
